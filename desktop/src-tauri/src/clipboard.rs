//! Host-confirmed text import and shared pasteboard helpers for optional session history.
//! Only opt-in history monitors; writes require explicit host controls.
use std::sync::{
    atomic::{AtomicBool, Ordering},
    Arc,
};

pub const WIDGET_ID: &str = "com.pinwall.clipboard-note";
const MAX_BYTES: usize = 64 * 1024;

#[cfg(any(target_os = "macos", test))]
fn validate_text(text: String) -> Result<String, String> {
    if text.len() > MAX_BYTES {
        return Err("clipboard_too_large".into());
    }
    if text.trim().is_empty() {
        return Err("clipboard_empty".into());
    }
    Ok(text)
}

#[cfg(any(target_os = "macos", test))]
fn sensitive_type(name: &str) -> bool {
    matches!(
        name,
        "org.nspasteboard.ConcealedType"
            | "org.nspasteboard.TransientType"
            | "org.nspasteboard.AutoGeneratedType"
    )
}

fn require_main(label: &str) -> Result<(), String> {
    if label == "main" {
        Ok(())
    } else {
        Err("clipboard_permission_denied".into())
    }
}

#[derive(Default)]
pub struct ClipboardService(Arc<AtomicBool>);
pub(crate) struct ReadGuard(Arc<AtomicBool>);
impl Drop for ReadGuard {
    fn drop(&mut self) {
        self.0.store(false, Ordering::Release);
    }
}
impl ClipboardService {
    pub(crate) fn acquire(&self) -> Result<ReadGuard, String> {
        self.0
            .compare_exchange(false, true, Ordering::AcqRel, Ordering::Acquire)
            .map_err(|_| "clipboard_busy")?;
        Ok(ReadGuard(self.0.clone()))
    }
}

#[cfg(target_os = "macos")]
pub(crate) fn change_count() -> isize {
    objc2::rc::autoreleasepool(|_| objc2_app_kit::NSPasteboard::generalPasteboard().changeCount())
}

#[cfg(target_os = "macos")]
pub(crate) fn changed_text(previous: isize) -> Option<(isize, Result<String, String>)> {
    objc2::rc::autoreleasepool(|_| {
        let pasteboard = objc2_app_kit::NSPasteboard::generalPasteboard();
        let count = pasteboard.changeCount();
        if count == previous {
            None
        } else {
            Some((count, macos::read(&pasteboard)))
        }
    })
}

#[cfg(target_os = "macos")]
pub(crate) fn write_confirmed_text(text: &str) -> Result<(), String> {
    use objc2_app_kit::{NSPasteboard, NSPasteboardTypeString};
    use objc2_foundation::NSString;
    objc2::rc::autoreleasepool(|_| {
        let pasteboard = NSPasteboard::generalPasteboard();
        pasteboard.clearContents();
        // SAFETY: AppKit's exported string constant is valid for the process lifetime.
        if pasteboard
            .setString_forType(&NSString::from_str(text), unsafe { NSPasteboardTypeString })
        {
            Ok(())
        } else {
            Err("history_unavailable".into())
        }
    })
}

#[tauri::command]
pub async fn read_widget_clipboard_text(
    window: tauri::WebviewWindow,
    app: tauri::AppHandle,
    widget_id: String,
    state: tauri::State<'_, ClipboardService>,
) -> Result<String, String> {
    require_main(window.label())?;
    if widget_id != WIDGET_ID {
        return Err("clipboard_permission_denied".into());
    }
    crate::widgets::verify_clipboard_widget(&app)?;
    let guard = state.acquire()?;
    // Pasteboard providers can block. Keep work off the UI thread, with at most one read.
    tauri::async_runtime::spawn_blocking(move || {
        let _guard = guard;
        #[cfg(target_os = "macos")]
        {
            objc2::rc::autoreleasepool(|_| {
                macos::read(&objc2_app_kit::NSPasteboard::generalPasteboard())
            })
        }
        #[cfg(not(target_os = "macos"))]
        {
            Err("clipboard_unsupported".into())
        }
    })
    .await
    .map_err(|_| "clipboard_unavailable".to_string())?
}

#[cfg(target_os = "macos")]
mod macos {
    use super::*;
    use objc2_app_kit::{NSPasteboard, NSPasteboardTypeString};

    pub(super) fn read(pasteboard: &NSPasteboard) -> Result<String, String> {
        let change_count = pasteboard.changeCount();
        if let Some(types) = pasteboard.types() {
            for data_type in types.iter() {
                if sensitive_type(&data_type.to_string()) {
                    return Err("clipboard_sensitive".into());
                }
            }
        }
        // SAFETY: this framework-owned constant is valid for the application's lifetime.
        let text = pasteboard
            .stringForType(unsafe { NSPasteboardTypeString })
            .ok_or("clipboard_empty")?;
        if text.length() > MAX_BYTES {
            return Err("clipboard_too_large".into());
        }
        // A concurrent clipboard change must not bypass sensitive-type checks.
        if pasteboard.changeCount() != change_count {
            return Err("clipboard_changed".into());
        }
        validate_text(text.to_string())
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn rejects_empty_and_oversized_text_without_truncating() {
        assert_eq!(validate_text("Hello\n你好".into()).unwrap(), "Hello\n你好");
        for text in [
            "".into(),
            " \n\t".into(),
            "x".repeat(MAX_BYTES + 1),
            "你".repeat(MAX_BYTES / 2),
        ] {
            assert!(validate_text(text).is_err());
        }
    }
    #[test]
    fn private_or_generated_clipboard_types_are_not_imported() {
        for name in [
            "org.nspasteboard.ConcealedType",
            "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType",
        ] {
            assert!(sensitive_type(name));
        }
        assert!(!sensitive_type("public.utf8-plain-text"));
        assert!(require_main("settings").is_err());
        assert!(require_main("notification").is_err());
        assert!(require_main("main").is_ok());
    }
    #[test]
    fn only_one_native_read_may_be_outstanding() {
        let service = ClipboardService::default();
        let guard = service.acquire().unwrap();
        assert!(service.acquire().is_err());
        drop(guard);
        assert!(service.acquire().is_ok());
    }
    #[cfg(target_os = "macos")]
    #[test]
    #[ignore = "Exercises a private named pasteboard, never the user's clipboard"]
    fn native_clipboard_smoke() {
        objc2::rc::autoreleasepool(|_| {
            use objc2_app_kit::{NSPasteboard, NSPasteboardTypeString};
            use objc2_foundation::NSString;
            let pasteboard = NSPasteboard::pasteboardWithUniqueName();
            pasteboard.clearContents();
            // SAFETY: AppKit exports a static string; the framework is linked for this target.
            let text_type = unsafe { NSPasteboardTypeString };
            assert!(pasteboard
                .setString_forType(&NSString::from_str("PinWall private test\n你好"), text_type));
            let result = macos::read(&pasteboard);
            assert!(pasteboard.setString_forType(
                &NSString::from_str("private"),
                &NSString::from_str("org.nspasteboard.ConcealedType")
            ));
            let sensitive = macos::read(&pasteboard);
            pasteboard.clearContents();
            assert_eq!(result.unwrap(), "PinWall private test\n你好");
            assert_eq!(sensitive.unwrap_err(), "clipboard_sensitive");
        });
    }
}
